namespace Boutquin.Trading.Application.EventHandlers;

using Boutquin.Trading.Application.Helpers;

/// <summary>
/// The SignalEventHandler class is an implementation of the IEventHandler interface that handles SignalEvent objects.
/// SignalEvent objects represent the trading signals generated by a trading strategy.
/// </summary>
/// <remarks>
/// This class handles SignalEvent objects by computing the position sizes for the assets based on the signals,
/// and generating OrderEvent objects for each asset. The OrderEvent objects are then passed to the EventProcessor for further processing.
/// The IPortfolio object that is passed to the SignalEventHandler constructor is used to get the strategy and the historical market data.
/// 
/// When an order settles in a currency the strategy does not hold enough of, the handler first emits
/// the <see cref="FxOrderEvent"/>s that <see cref="Helpers.FxFundingPlanner"/> plans under its
/// <see cref="FxFundingPolicy"/>, so the brokerage converts the cash between that bar's asset sells
/// and asset buys. A single-currency portfolio never triggers this path.
///
/// Here is an example of how to use this class:
/// <code>
/// var portfolio = new Portfolio();
/// var signalEventHandler = new SignalEventHandler();
/// 
/// var signalEvent = new SignalEvent();
/// await signalEventHandler.HandleEventAsync(portfolio, signalEvent);
/// </code>
/// </remarks>
public sealed class SignalEventHandler : IEventHandler
{
    private readonly FxFundingPolicy _fxFundingPolicy;

    /// <summary>
    /// Initializes a new instance of the <see cref="SignalEventHandler"/> class.
    /// </summary>
    /// <param name="fxFundingPolicy">How orders in a currency the strategy holds too little of are funded. Defaults to <see cref="FxFundingPolicy.FundShortfall"/>.</param>
    /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="fxFundingPolicy"/> is not a defined value.</exception>
    public SignalEventHandler(FxFundingPolicy fxFundingPolicy = FxFundingPolicy.FundShortfall)
    {
        Guard.AgainstUndefinedEnumValue(() => fxFundingPolicy);
        _fxFundingPolicy = fxFundingPolicy;
    }

    /// <summary>
    /// Handles the provided SignalEvent object.
    /// </summary>
    /// <param name="portfolio">The portfolio for which the event is relevant.</param>
    /// <param name="eventObj">The SignalEvent object to handle.</param>
    /// <param name="cancellationToken">A token to cancel the async operation.</param>
    /// <exception cref="ArgumentNullException">
    /// Thrown when portfolio is null.
    /// </exception>
    /// <exception cref="ArgumentException">
    /// Thrown when eventObj is not a SignalEvent object.
    /// </exception>
    /// <returns>A Task representing the asynchronous operation.</returns>
    /// <remarks>
    /// The HandleEventAsync method computes the position sizes for the assets based on the signals,
    /// and generates OrderEvent objects for each asset. The OrderEvent objects are then passed to the EventProcessor for further processing.
    /// The portfolio is retrieved from the portfolio that was passed to the SignalEventHandler constructor.
    /// </remarks>
    public async Task HandleEventAsync(IPortfolio portfolio, IFinancialEvent eventObj, CancellationToken cancellationToken)
    {
        Guard.AgainstNull(() => portfolio); // Throws ArgumentNullException

        var signalEvent = eventObj as SignalEvent
            ?? throw new ArgumentException("Event must be of type SignalEvent.", nameof(eventObj));

        cancellationToken.ThrowIfCancellationRequested();

        // Call methods on the Portfolio class to perform the necessary actions
        var strategy = portfolio.GetStrategy(signalEvent.StrategyName);

        // Compute the position sizes for the assets based on the signals.
        var positionSizes = strategy.PositionSizer.ComputePositionSizes(
            signalEvent.Timestamp,
            signalEvent.Signals,
            strategy,
            portfolio.HistoricalMarketData,
            portfolio.HistoricalFxConversionRates);

        // Iterate through the assets and generate OrderEvents for each asset.
        var orderEvents = new List<OrderEvent>();
        foreach (var asset in signalEvent.Signals.Keys)
        {
            // ERR-A03: Use TryGetValue with meaningful error
            if (!positionSizes.TryGetValue(asset, out var desiredPositionSize))
            {
                throw new InvalidOperationException($"Position size not computed for asset \'{asset}\' in strategy \'{signalEvent.StrategyName}\'.");
            }

            // Get the current position size for the current asset.
            // Safe: first trade for asset starts with zero position (no prior holdings)
            var currentPositionSize = strategy.Positions.GetValueOrDefault(asset, 0);

            // Calculate the order size based on the difference between the desired position size and the current position size.
            var orderSize = desiredPositionSize - currentPositionSize;

            // If the order size is zero, no order needs to be placed.
            if (orderSize == 0)
            {
                continue;
            }

            // Determine the trade action based on the order size.
            var tradeAction = orderSize > 0 ? TradeAction.Buy : TradeAction.Sell;

            // Calculate the order prices for the current asset.
            var (orderType, primaryPrice, secondaryPrice) =
                strategy.OrderPriceCalculationStrategy.CalculateOrderPrices(
                    signalEvent.Timestamp,
                    asset,
                    tradeAction,
                    portfolio.HistoricalMarketData);

            // Create an OrderEvent for the current asset.
            orderEvents.Add(new OrderEvent(
                signalEvent.Timestamp,
                signalEvent.StrategyName,
                asset,
                tradeAction,
                orderType,
                Math.Abs(orderSize),
                primaryPrice,
                secondaryPrice));
        }

        // FX conversions go out first so the brokerage fills them between this bar's asset sells
        // and asset buys; the asset orders then find the cash they need in the right currency.
        var fxOrders = FxFundingPlanner.Plan(
            signalEvent.Timestamp,
            strategy,
            portfolio.BaseCurrency,
            ExpectedTradeCashFlows(portfolio, strategy, orderEvents),
            portfolio.HistoricalFxConversionRates,
            _fxFundingPolicy);

        foreach (var fxOrder in fxOrders)
        {
            await portfolio.EventProcessor.ProcessEventAsync(fxOrder, cancellationToken).ConfigureAwait(false);
        }

        foreach (var orderEvent in orderEvents)
        {
            // Pass the OrderEvent to the EventProcessor for further processing.
            await portfolio.EventProcessor.ProcessEventAsync(orderEvent, cancellationToken).ConfigureAwait(false);
        }
    }

    /// <summary>
    /// Sums, per currency, the cash the orders are expected to move at signal-bar prices — sell
    /// proceeds positive, buy costs negative. The order's primary price is the estimate (the close
    /// for a market order, the limit or stop otherwise); an order without one is priced at the
    /// asset's most recent bar.
    /// </summary>
    internal static IReadOnlyDictionary<Currency, decimal> ExpectedTradeCashFlows(
        IPortfolio portfolio,
        IStrategy strategy,
        IEnumerable<OrderEvent> orderEvents)
    {
        var flows = new Dictionary<Currency, decimal>();
        foreach (var order in orderEvents)
        {
            var price = order.PrimaryPrice
                ?? Strategies.HistoricalMarketDataLookup.TryFindMostRecentBar(portfolio.HistoricalMarketData, order.Symbol, order.Timestamp)?.AdjustedClose
                ?? throw new InvalidOperationException($"Cannot estimate the cash flow of the {order.TradeAction} order for '{order.Symbol}' on {order.Timestamp}: no price.");

            var currency = strategy.Assets.TryGetValue(order.Symbol, out var tracked)
                ? tracked
                : portfolio.GetAssetCurrency(order.Symbol);

            var amount = price * order.Quantity;
            flows[currency] = flows.GetValueOrDefault(currency, 0m) + (order.TradeAction == TradeAction.Sell ? amount : -amount);
        }

        return flows;
    }
}
